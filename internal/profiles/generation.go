// GenerationStampFileName is generator metadata, not part of the instruction
// body. Keeping it separate preserves profile byte ceilings and @-include text.
const GenerationStampFileName = ".generated.json"

const generationLockName = ".generation.lock"

type generationStamp struct {
	Version string            `json:"version"`
	Files   map[string]string `json:"files"`
}

var generationMu sync.Mutex

// legacyGeneratedHashes recognizes exact un-stamped bodies from public releases
// v0.64.10 (defa9f8e) and v0.64.11 (c7abb9b9). The latter is byte-identical to
// the pre-change eb0e7ee1 shared producers. Never infer ownership from a heading.
var legacyGeneratedHashes = map[string][]string{
	"core.md":         {"833ba7112712e122050cb31b40c4d233651a8096f4dc5064051e45cc0811e172", "eb00d8b77fecf1e5d81025ade2683539d86a4b7acd8d82be9b8853388733dcb5"},
	"full.md":         {"74bda77173fc2bbbda303c30066031829e7f2288b618c89a48d260d8a709d99a", "4d3d0577d088578ffdf83287bd468ac6d627c19a2f9dcbe44f99f1fb1994a219"},
	"localization.md": {"e0fe619f5f6535bd83d1afc2eb43525ec43f79e956e32b3272788cbcff948c27", "df16fabe37b56fa7811aa7da3a7a101c65e03a910ab071c015cf6b059914adde"},
}

// RegenerateIfNeeded refreshes an existing managed installation. It never
// installs profiles just because a daemon starts. Modified/unrecognized files
// are preserved and returned as actionable errors; daemon callers log and proceed.
func RegenerateIfNeeded(dir, binaryVersion string) (bool, error) {
	if strings.TrimSpace(binaryVersion) == "" {
		return false, errors.New("profile refresh requires the running binary version")
	}
	if _, err := os.Lstat(dir); errors.Is(err, os.ErrNotExist) {
		return false, nil
	} else if err != nil {
		return false, err
	}
	return rewriteGeneratedProfiles(dir, "", binaryVersion, true)
}

func optionalBinaryVersion(versions []string) string {
	if len(versions) == 0 {
		return ""
	}
	return strings.TrimSpace(versions[0])
}

func rewriteGeneratedProfiles(dir, selection, version string, automatic bool) (changed bool, err error) {
	generationMu.Lock()
	defer generationMu.Unlock()
	if info, statErr := os.Lstat(dir); statErr == nil {
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return false, fmt.Errorf("instruction directory %s is not a regular directory", dir)
		}
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return false, statErr
	} else if err := os.MkdirAll(dir, 0o755); err != nil {
		return false, err
	}
	if automatic {
		found := false
		for _, name := range append(profileFileNames(), ActiveFileName, GenerationStampFileName) {
			if _, statErr := os.Lstat(filepath.Join(dir, name)); statErr == nil {
				found = true
			} else if !errors.Is(statErr, os.ErrNotExist) {
				return false, statErr
			}
		}
		if !found {
			return false, nil
		}
	}
	// Actual CLI/daemon callers supply a version and serialize across processes.
	// An unversioned library/render call must not invent a binary identity or
	// introduce stamp/lock artifacts into the unchanged policy render fence.
	if version != "" {
		lockPath := filepath.Join(dir, generationLockName)
		if _, _, err := readManagedFile(lockPath); err != nil {
			return false, err
		}
		lock := flock.New(lockPath)
		locked, lockErr := lock.TryLock()
		if lockErr != nil || !locked {
			_ = lock.Close()
			return false, fmt.Errorf("instruction generation is busy; retry later: %w", errors.Join(lockErr, errors.New("profile lock unavailable")))
		}
		defer func() { err = errors.Join(err, lock.Close()) }()
	}
	stamp, err := readGenerationStamp(dir)
	if err != nil {
		return false, err
	}
	current := make(map[string][]byte)
	for _, profile := range Table() {
		current[profile.Name+".md"] = []byte(profile.Body())
	}
	current[ActiveFileName] = nil
	existing := make(map[string][]byte)
	for name := range current {
		body, present, err := readManagedFile(filepath.Join(dir, name))
		if err != nil {
			return false, err
		}
		if present {
			existing[name] = body
		}
	}
	if automatic && len(existing) == 0 && stamp == nil {
		return false, nil
	}
	selected := selection
	if selected == "" {
		selected, err = storedActiveName(dir)
		if err != nil {
			return false, err
		}
	} else if _, _, err := readManagedFile(filepath.Join(dir, stateFileName)); err != nil {
		// An explicit switch can replace corrupt selection metadata, but must
		// still refuse a linked/device state path rather than overwrite it.
		return false, err
	}
	current[ActiveFileName] = current[selected+".md"]
	// Accept recorded-old OR exact-current generated bytes. A process can die
	// between the per-file atomic replacements and the final stamp write; mixed
	// old/new managed content is recoverable without treating a user edit as ours.
	for name, body := range existing {
		if !ownedGeneratedBody(name, body, current, stamp) {
			return false, fmt.Errorf("instruction file %s has custom or unrecognized content; back it up and move it aside before running gortex instructions regen", filepath.Join(dir, name))
		}
	}
	newStamp := generationStamp{Version: version, Files: make(map[string]string)}
	for _, name := range append(append([]string(nil), profileFileNames()...), ActiveFileName) {
		body := current[name]
		newStamp.Files[name] = generatedHash(body)
		if old, present := existing[name]; !present || string(old) != string(body) {
			if err := writeIfChanged(filepath.Join(dir, name), body); err != nil {
				return changed, err
			}
			changed = true
		}
	}
	if version != "" {
		data, marshalErr := json.MarshalIndent(newStamp, "", "  ")
		if marshalErr != nil {
			return changed, marshalErr
		}
		if stamp == nil || stamp.Version != version || !sameGeneratedHashes(stamp.Files, newStamp.Files) {
			if err := writeIfChanged(filepath.Join(dir, GenerationStampFileName), append(data, '\n')); err != nil {
				return changed, err
			}
			changed = true
		}
	}
	if selection != "" {
		data, marshalErr := json.Marshal(state{Name: selected, SwitchedAt: time.Now().UTC().Format(time.RFC3339)})
		if marshalErr != nil {
			return changed, marshalErr
		}
		if err := writeIfChanged(filepath.Join(dir, stateFileName), append(data, '\n')); err != nil {
			return changed, err
		}
	}
	return changed, nil
}

func profileFileNames() []string {
	names := make([]string, 0, len(Table()))
	for _, profile := range Table() {
		names = append(names, profile.Name+".md")
	}
	return names
}

func generatedHash(body []byte) string {
	digest := sha256.Sum256(body)
	return hex.EncodeToString(digest[:])
}

func ownedGeneratedBody(name string, body []byte, current map[string][]byte, stamp *generationStamp) bool {
	hash := generatedHash(body)
	if stamp != nil && stamp.Files[name] == hash {
		return true
	}
	if name != ActiveFileName {
		return generatedHash(current[name]) == hash || containsGeneratedHash(legacyGeneratedHashes[name], hash)
	}
	// active.md is a byte copy of any generated profile, never a custom body.
	// This also recovers a switch interrupted before active.json was committed.
	for _, file := range profileFileNames() {
		if generatedHash(current[file]) == hash || containsGeneratedHash(legacyGeneratedHashes[file], hash) {
			return true
		}
	}
	return false
}

func containsGeneratedHash(hashes []string, want string) bool {
	for _, hash := range hashes {
		if hash == want {
			return true
		}
	}
	return false
}

func readManagedFile(path string) ([]byte, bool, error) {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, err
	}
	if !info.Mode().IsRegular() || info.Size() > 64*1024 {
		return nil, false, fmt.Errorf("instruction artifact %s is not a bounded regular file; preserve it and review before regeneration", path)
	}
	data, err := os.ReadFile(path)
	return data, true, err
}

func readGenerationStamp(dir string) (*generationStamp, error) {
	data, exists, err := readManagedFile(filepath.Join(dir, GenerationStampFileName))
	if err != nil || !exists {
		return nil, err
	}
	var stamp generationStamp
	decoder := json.NewDecoder(strings.NewReader(string(data)))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&stamp); err != nil {
		return nil, fmt.Errorf("invalid instruction generation stamp; preserve it and review before regeneration: %w", err)
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return nil, errors.New("instruction generation stamp must contain one JSON object")
	}
	if stamp.Version == "" || len(stamp.Files) != len(Table())+1 {
		return nil, errors.New("incomplete instruction generation stamp; preserve it and review before regeneration")
	}
	for _, name := range append(profileFileNames(), ActiveFileName) {
		decoded, err := hex.DecodeString(stamp.Files[name])
		if err != nil || len(decoded) != sha256.Size {
			return nil, errors.New("invalid managed-file hash in instruction generation stamp")
		}
	}
	return &stamp, nil
}

func sameGeneratedHashes(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for name, hash := range a {
		if b[name] != hash {
			return false
		}
	}
	return true
}

func storedActiveName(dir string) (string, error) {
	data, present, err := readManagedFile(filepath.Join(dir, stateFileName))
	if err != nil {
		return "", err
	}
	if !present {
		return DefaultName, nil
	}
	var selected state
	if json.Unmarshal(data, &selected) != nil {
		return "", errors.New("cannot preserve invalid active profile selection; review active.json before regenerating")
	}
	if _, ok := ByName(selected.Name); !ok {
		return "", errors.New("cannot preserve unknown active profile selection; review active.json before regenerating")
	}
	return selected.Name, nil
}
