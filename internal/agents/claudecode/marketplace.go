package claudecode

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
)

// marketplaceName is the id users type after "@" when installing:
// `claude plugin install gortex@gortex`.
const marketplaceName = "gortex"

// marketplacePluginSource is the plugin entry's source, relative to the
// marketplace root. A plugins/<name>/ layout leaves room for more
// plugins in the same marketplace later.
const marketplacePluginSource = "./plugins/" + pluginName

const (
	marketplaceDescription       = "Gortex plugins for Claude Code: graph-based code intelligence served by a local daemon."
	marketplacePluginDescription = "Graph-based code intelligence for Claude Code: MCP tools, workflow skills, sub-agents and hooks backed by the local Gortex daemon."
)

// marketplaceReadmeBody is the README at the marketplace root, which is
// also the landing page of the published gortexhq/claude-plugin repo.
const marketplaceReadmeBody = `# Gortex plugins for Claude Code

This repository is a Claude Code plugin marketplace. It is generated by
` + "`gortex plugin emit`" + ` from https://github.com/zzet/gortex, so change the
source there rather than editing it here.

## Install

The plugin runs the ` + "`gortex`" + ` binary, so install that first
(https://github.com/zzet/gortex/blob/main/docs/installation.md). Then:

` + "```sh\nclaude plugin marketplace add gortexhq/claude-plugin\nclaude plugin install gortex@gortex\n```" + `

If you also run ` + "`gortex install`" + ` or ` + "`gortex init`" + `, pass
` + "`--agents-skip claude-code`" + ` so Gortex is not registered twice. See the
plugin README for what that skips.

## Plugins

| Plugin | What it adds |
|--------|--------------|
| [` + "`gortex`" + `](plugins/gortex/) | MCP server, workflow skills (` + "`/gortex:explore`" + `, ` + "`/gortex:impact`" + `, ...), sub-agents and hooks |
`

// EmitMarketplace writes a Claude Code plugin marketplace under
// spec.TargetDir: .claude-plugin/marketplace.json, a README and LICENSE
// at the root, and the plugin itself under plugins/gortex/. Returns the
// paths written, relative to TargetDir, in stable order.
//
// A target that still holds a bundle from before the marketplace
// layout, with the plugin at its root, is refused rather than cleaned:
// the emitter cannot tell its own old files from files someone added.
func EmitMarketplace(spec PluginBundleSpec) ([]string, error) {
	if spec.TargetDir == "" {
		return nil, fmt.Errorf("EmitMarketplace: TargetDir is required")
	}
	flatManifest := filepath.Join(spec.TargetDir, ".claude-plugin", "plugin.json")
	if _, err := os.Lstat(flatManifest); err == nil {
		return nil, fmt.Errorf("%s holds a plugin bundle from the older flat layout; remove it or emit into an empty directory", spec.TargetDir)
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("check %s: %w", flatManifest, err)
	}

	pluginSpec := spec
	pluginSpec.TargetDir = filepath.Join(spec.TargetDir, filepath.FromSlash(marketplacePluginSource))
	pluginFiles, err := EmitPluginBundle(pluginSpec)
	if err != nil {
		return nil, err
	}

	manifest := map[string]any{
		"name":        marketplaceName,
		"description": marketplaceDescription,
		"owner": map[string]any{
			"name":  pluginAuthorName,
			"email": pluginAuthorEmail,
		},
		"plugins": []any{
			map[string]any{
				"name":        pluginName,
				"source":      marketplacePluginSource,
				"description": marketplacePluginDescription,
			},
		},
	}
	manifestJSON, err := marshalJSONStable(manifest)
	if err != nil {
		return nil, fmt.Errorf("marshal marketplace.json: %w", err)
	}

	root := []struct {
		rel  string
		body []byte
	}{
		{".claude-plugin/marketplace.json", manifestJSON},
		{"README.md", []byte(marketplaceReadmeBody)},
		{"LICENSE", []byte(pluginLicenseBody)},
	}
	written := make([]string, 0, len(root)+len(pluginFiles))
	for _, f := range root {
		full := filepath.Join(spec.TargetDir, f.rel)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return nil, fmt.Errorf("mkdir %s: %w", filepath.Dir(f.rel), err)
		}
		if err := os.WriteFile(full, f.body, 0o644); err != nil {
			return nil, fmt.Errorf("write %s: %w", f.rel, err)
		}
		written = append(written, f.rel)
	}
	for _, rel := range pluginFiles {
		written = append(written, filepath.Join(filepath.FromSlash(marketplacePluginSource), rel))
	}
	return written, nil
}
